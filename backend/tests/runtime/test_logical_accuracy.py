def test_logical_reasoning_pipeline():
    from concurrent.futures import ThreadPoolExecutor, as_completed

    success_count = 0
    total_latency = 0.0
    completed_cases = []

    print("\n" + "="*30 + " RUNNING 100 FACTUAL/LOGICAL ACCURACY TESTS IN PARALLEL " + "="*30)

    # Prepare cases with index
    indexed_cases = [(i, case) for i, case in enumerate(TEST_CASES, 1)]

    def execute_one_case(item):
        i, (query, expected_keywords, topic) = item
        start_time = time.time()
        
        response = client.post(
            "/chat",
            json={
                "message": query,
                "skill": "quick",
                "session_id": f"test_session_{i}",
                "user_id": f"test_user_{i}"
            }
        )
        
        latency = (time.time() - start_time) * 1000
        data = response.json()
        reply = data.get("reply", "")

        passed = any(kw.lower() in reply.lower() for kw in expected_keywords)
        return i, query, reply, passed, latency, topic

    # Execute with 10 threads
    with ThreadPoolExecutor(max_workers=10) as executor:
        futures = {executor.submit(execute_one_case, item): item for item in indexed_cases}
        
        for future in as_completed(futures):
            i, query, reply, passed, latency, topic = future.result()
            total_latency += latency
            status_str = "PASS" if passed else "FAIL"
            if passed:
                success_count += 1
            print(f"[{i}/100] Topic: {topic} | Query: '{query}' | Reply: '{reply}' | Status: {status_str} | Latency: {latency:.1f}ms")

    avg_latency = total_latency / len(TEST_CASES)
    success_rate = (success_count / len(TEST_CASES)) * 100

    print("="*80)
    print(f"TOTAL CASES: {len(TEST_CASES)}")
    print(f"SUCCESSFUL: {success_count} / {len(TEST_CASES)} ({success_rate:.1f}%)")
    print(f"AVERAGE LATENCY: {avg_latency:.1f}ms")
    print("="*80)

    assert success_rate >= 80.0
